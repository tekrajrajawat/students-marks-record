students = []

def add_student():
    name = input("Name: ").strip().title()
    try:
        marks = int(input("Marks (0-100): "))
    except ValueError:
        print("Marks must be a whole number")
        return
    if marks < 0 or marks > 100:
        print("Marks must be between 0 and 100")
        return
    students.append({"name": name, "marks": marks})
    print("Student added")

def view_students():
    if len(students) == 0:
        print("No students yet")
        return
    for s in students:
        print(f"{s['name']}: {s['marks']}")

def main():
    while True:
        print()
        print("1. Add student")
        print("2. View all students")
        print("3. Quit")
        choice = input("Choose: ").strip()

        if choice == "1":
            add_student()
        elif choice == "2":
            view_students()
        elif choice == "3":
            break
        else:
            print("Invalid choice")

    print("Goodbye")

main()

def search_student():
    name = input("Name to search: ").strip().title()
    for s in students:
        if s["name"] == name:
            print(f"{s['name']}: {s['marks']}")
            return
    print("Not found")

def show_stats():
    if len(students) == 0:
        print("No students yet")
        return
    total = 0
    top = students[0]
    for s in students:
        total = total + s["marks"]
        if s["marks"] > top["marks"]:
            top = s
    average = total / len(students)
    print(f"Average: {average:.2f}")
    print(f"Topper: {top['name']} ({top['marks']})")

def delete_student():
    name = input("Name to delete: ").strip().title()
    for s in students:
        if s["name"] == name:
            students.remove(s)
            print("Deleted")
            return
    print("Not found")

def main():
    while True:
        print()
        print("1. Add student")
        print("2. View all students")
        print("3. Search student")
        print("4. Show average and topper")
        print("5. Delete student")
        print("6. Quit")
        choice = input("Choose: ").strip()

        if choice == "1":
            add_student()
        elif choice == "2":
            view_students()
        elif choice == "3":
            search_student()
        elif choice == "4":
            show_stats()
        elif choice == "5":
            delete_student()
        elif choice == "6":
            break
        else:
            print("Invalid choice")

    print("Goodbye")

main()

